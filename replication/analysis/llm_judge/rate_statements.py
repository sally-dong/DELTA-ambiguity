"""LLM-as-a-judge baseline ratings (the paper's two direct-rating rubrics).

Rates each policy statement on a 1-7 scale from its text alone — no cases, no
rater personas. Two rubrics, selected via --property:

    ambiguity   dictionary-style clarity/vagueness (1 = clear, 7 = vague)
    delta       "consequential ambiguity": how much stakeholder disagreement
                would arise when classifying concrete actions against the
                statement (mirrors the DELTA mechanism, but as a single
                direct judgment)

The paper uses three judges per rubric, each run separately:

    rate_statements.py --property <rubric> --model gpt-5.2
    rate_statements.py --property <rubric> --model gpt-5 --thinking
    rate_statements.py --property <rubric> --model gemini-3-pro-preview --thinking

gpt-5.2 runs with thinking disabled at temperature 0 and records top-20 token
logprobs; the thinking models run at temperature 1 with medium effort and
report a single sampled rating. Judge inference goes through `delta.inference`
(the same machinery as the DELTA runs) and reads OPENAI_API_KEY /
GEMINI_API_KEY from the environment.

Input CSV schema: question, candidate_id, iteration, round_id,
is_top_candidate, text. `analysis/adversarial/adversarial_policies.csv` is
committed; the human-experiment input is generated by
`build_human_experiment_input.py` in this directory.

Output layout (matches the committed `analysis/*/llm_ratings/` directories):

    {out_dir}/prompt.md                    exact rubric used for the run
    {out_dir}/{model}/ratings_raw.csv      one row per statement: rating,
                                           candidate_id, iteration, round_id,
                                           and prob_1..prob_7 in logprobs mode
    {out_dir}/{model}/...                  raw dumps written by run_inference

custom_ids are parsed back with an anchored regex rather than
delta.inference.parse_custom_ids, which splits on '_' and mangles round_ids
that contain underscores (e.g. "human_experiment").
"""

import argparse
import os
import re
from typing import Optional

import numpy as np
import pandas as pd

from delta.inference import run_inference

